import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
const base = 'http://127.0.0.1:18001';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const checks = [];
try {
  expect((await context.request.get(base + '/api/quota/meta')).status()).toBe(401);
  expect((await context.request.get(base + '/api/session')).status()).toBe(401);
  checks.push('Anonymous quota API and session rejected');
  const secret = JSON.parse(execFileSync('kubectl', ['--context', 'higress-dev', '-n', 'higress-system', 'get', 'secret', 'higress-console', '-o', 'json'], { encoding: 'utf8' })).data;
  expect((await context.request.post(base + '/session/login', { data: { username: Buffer.from(secret.adminUsername, 'base64').toString(), password: Buffer.from(secret.adminPassword, 'base64').toString() } })).ok()).toBeTruthy();
  const page = await context.newPage();
  await page.goto(base + '/walmart-quota/overview');
  await expect(page.getByRole('heading', { name: '用量总览', exact: true })).toBeVisible();
  await expect(page.getByLabel('管理员密码')).toHaveCount(0);
  await expect(page.getByRole('button', { name: /退出额度登录|进入额度管理/ })).toHaveCount(0);
  expect((await context.cookies()).some(c => c.name === 'portal_session')).toBeFalsy();
  checks.push('Console login directly opens quota without password or Portal cookie');
  const session = await (await context.request.get(base + '/api/session')).json();
  expect(session.auth).toBe('console');
  expect((await context.request.get(base + '/api/quota/meta')).status()).toBe(200);
  checks.push('Authenticated quota reads work');
  const post = (path, headers = {}) => context.request.post(base + path, { headers: { Origin: base, ...headers }, data: {} });
  expect((await post('/api/quota/assign')).status()).toBe(403);
  expect((await post('/api/quota/unknown', { 'x-portal-csrf': session.csrf })).status()).toBe(404);
  expect((await post('/api/quota/unknown', { 'x-portal-csrf': session.csrf, Origin: 'https://example.invalid' })).status()).toBe(403);
  checks.push('CSRF and Origin still enforced');
  expect((await post('/api/login')).status()).toBe(404);
  expect((await post('/api/logout')).status()).toBe(404);
  checks.push('Independent quota login and logout disabled in Console');
  await fs.mkdir('docs/evidence-console-auth', { recursive: true });
  await page.screenshot({ path: 'docs/evidence-console-auth/overview.png', fullPage: true });
  const cookies = await context.cookies();
  await context.clearCookies();
  await context.addCookies(cookies.filter(c => c.name === 'JSESSIONID'));
  expect((await context.request.get(base + '/api/session')).status()).toBe(401);
  expect((await context.request.get(base + '/api/quota/meta')).status()).toBe(401);
  checks.push('CSRF session alone cannot bypass Console authentication');
  await page.reload();
  await expect(page.getByLabel('管理员密码')).toHaveCount(0);
  await fs.writeFile('docs/evidence-console-auth/report.json', JSON.stringify({ checks }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
} finally { await browser.close(); }
